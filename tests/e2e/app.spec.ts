 await page.reload();await page.getByRole('button',{name:'Deck builder',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Deck name'})).toHaveValue('Playwright crew');
 await expect(page.locator('.deck-row')).toHaveCount(1);
