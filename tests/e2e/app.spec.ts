import {test,expect} from '@playwright/test';
test('card filters, exact artwork, and leader details work',async({page})=>{
 await page.goto('/');
 await page.getByRole('textbox',{name:'Search cards or sets'}).fill('OP17-001');
 await expect(page.locator('.card-tile')).toHaveCount(1);
 await page.getByRole('button',{name:'View Edward.Newgate OP17-001',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await expect(dialog).toBeVisible();
 await expect(dialog.getByText('Life',{exact:true}).locator('..').locator('strong')).toHaveText('5');
 await expect(dialog.getByText('Cost',{exact:true}).locator('..').locator('strong')).toHaveText('—');
 await expect.poll(()=>dialog.locator('img').evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
 await page.keyboard.press('Escape');
 await expect(dialog).not.toBeVisible();
 await page.getByRole('checkbox',{name:'Show alternate art'}).check();
 await expect(page.locator('.card-tile')).toHaveCount(2);
 await page.getByRole('checkbox',{name:'Show alternate art'}).uncheck();
 await page.getByRole('textbox',{name:'Search cards or sets'}).fill('P-001');
 await expect(page.locator('.card-tile')).toHaveCount(1);
 await expect.poll(()=>page.locator('.card-tile img').evaluate(i=>(i as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
});
