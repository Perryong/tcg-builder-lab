test('clearing a leader and replacing an empty edited draft are safe',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'Deck builder',exact:true}).click();
 await page.getByLabel('Choose leader',{exact:true}).selectOption('OP15-058');
 await page.getByLabel('Choose leader',{exact:true}).selectOption('');
 await expect(page.getByLabel('Choose leader',{exact:true})).toHaveValue('');
 await expect(page.getByRole('spinbutton',{name:'DON card count'})).toHaveValue('10');
 await page.getByRole('textbox',{name:'Deck name'}).fill('Unsaved empty crew');
 await page.getByRole('button',{name:'Meta & insights',exact:true}).click();
 let warned=false;page.once('dialog',async d=>{warned=true;await d.dismiss();});
 await page.getByRole('button',{name:'Try a list',exact:true}).first().click();
 expect(warned).toBe(true);
 await page.getByRole('button',{name:'Deck builder',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Deck name'})).toHaveValue('Unsaved empty crew');
});
